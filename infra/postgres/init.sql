CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number VARCHAR(20) NOT NULL UNIQUE,
    owner_name VARCHAR(100) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_vehicles_plate_number ON vehicles (plate_number);

CREATE TABLE IF NOT EXISTS parking_zones (
    zone_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_code VARCHAR(10) NOT NULL UNIQUE,
    zone_name VARCHAR(100) NOT NULL,
    hourly_rate NUMERIC(6,2) NOT NULL CHECK (hourly_rate >= 0),
    max_parking_minutes INTEGER NOT NULL CHECK (max_parking_minutes > 0)
);

CREATE TABLE IF NOT EXISTS parking_spaces (
    space_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_number VARCHAR(20) NOT NULL UNIQUE,
    zone_id INTEGER NOT NULL REFERENCES parking_zones (zone_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    street_name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_spaces_space_number ON parking_spaces (space_number);

CREATE TABLE IF NOT EXISTS parking_events (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles (vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    space_id INTEGER NOT NULL REFERENCES parking_spaces (space_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    customer_id VARCHAR(32),
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NULL,
    status VARCHAR(20) NOT NULL,
    calculated_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE parking_events ADD COLUMN IF NOT EXISTS customer_id VARCHAR(32);
CREATE INDEX IF NOT EXISTS idx_events_customer_active ON parking_events (customer_id, status) WHERE end_time IS NULL;

CREATE TABLE IF NOT EXISTS payment_transactions (
    transaction_id VARCHAR(64) PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES parking_events (event_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles (vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    space_id INTEGER NOT NULL REFERENCES parking_spaces (space_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    zone_code VARCHAR(10) NOT NULL,
    start_time TIMESTAMP NOT NULL,
    stop_time TIMESTAMP NOT NULL,
    amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_vehicle_id ON payment_transactions (vehicle_id);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_stop_time ON payment_transactions (stop_time DESC);

CREATE TABLE IF NOT EXISTS citations (
    citation_id VARCHAR(64) PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles (vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    space_id INTEGER NOT NULL REFERENCES parking_spaces (space_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    zone_code VARCHAR(10) NOT NULL,
    inspection_time TIMESTAMP NOT NULL,
    amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_citations_vehicle_id ON citations (vehicle_id);
CREATE INDEX IF NOT EXISTS idx_citations_inspection_time ON citations (inspection_time DESC);

CREATE TABLE IF NOT EXISTS customers (
    customer_id VARCHAR(32) PRIMARY KEY,
    vehicle_id INTEGER UNIQUE REFERENCES vehicles (vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    display_name VARCHAR(100) NOT NULL,
