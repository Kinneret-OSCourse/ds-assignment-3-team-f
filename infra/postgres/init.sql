INSERT INTO parking_spaces (space_number, zone_id, street_name, is_active)
SELECT
    'S' || LPAD((((zone_seed.zone_rank - 1) * 10) + slot.slot_number)::TEXT, 3, '0'),
    zone_seed.zone_id,
    zone_seed.zone_name || ' Street',
    TRUE
FROM (
    SELECT zone_id, zone_name, ROW_NUMBER() OVER (ORDER BY zone_code) AS zone_rank
    FROM parking_zones
) AS zone_seed
CROSS JOIN (
    SELECT generate_series(1, 10) AS slot_number
) AS slot
ON CONFLICT (space_number) DO NOTHING;
